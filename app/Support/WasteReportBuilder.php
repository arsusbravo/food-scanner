    public const FLW_MAPPING = [
        'protein' => ['group' => 'Meat & Seafood / Pulses', 'eu_code' => '02 02 / 20 01 08'],
        'veg' => ['group' => 'Vegetables & Fruits', 'eu_code' => '02 01 / 20 01 08'],
        'dairy' => ['group' => 'Dairy & Eggs', 'eu_code' => '02 05 / 20 01 08'],
        'prepared' => ['group' => 'Prepared & Processed Foods', 'eu_code' => '20 01 08'],
    ];

    /**
     * Indicative kg CO2e per kg of wasted food, averaged per category.
     * Shown as an estimate only.
     */
    public const CO2E_FACTORS = [
        'protein' => 15.0,
        'veg' => 1.5,
        'dairy' => 8.0,
        'prepared' => 5.0,
    ];

    /**
     * Aggregate columns needed to cost entries: entries with their own cost use
     * it, the rest fall back to the category price per kg.
     */
    public const COST_SELECT = 'SUM(CASE WHEN cost IS NOT NULL THEN cost ELSE 0 END) as entry_cost, '
        .'SUM(CASE WHEN cost IS NULL THEN weight_kg ELSE 0 END) as unpriced_kg, '
        .'COUNT(cost) as priced_count';

    /**
     * Cost of a group of entries. Null when nothing could be costed.
     */
    public static function categoryCost(float $entryCost, float $unpricedKg, int $pricedCount, mixed $price): ?float
    {
        $hasPrice = $price !== null && $price !== '';

        if ($pricedCount === 0 && ! $hasPrice) {
            return null;
        }

        return round($entryCost + ($hasPrice ? $unpricedKg * (float) $price : 0), 2);
    }

    /**
     * @param  Collection  $rows  category/reason aggregate rows
     *                            (total_kg, entry_count)
     * @param  array<string, float|int|string|null>|null  $prices  cost per kg keyed by category
     */
    public function buildSummary($rows, ?array $prices = null): array
    {
        $summary = [];

        foreach (array_keys(self::FLW_MAPPING) as $category) {
            $categoryRows = $rows->where('category', $category);
            $flw = self::FLW_MAPPING[$category];

            $byReason = [];
            foreach ($categoryRows as $row) {
                $byReason[$row->reason] = [
                    'total_kg' => round((float) $row->total_kg, 2),
                    'entry_count' => $row->entry_count,
                ];
            }

            $rawKg = (float) $categoryRows->sum('total_kg');
            $hasCostColumns = isset($categoryRows->first()->unpriced_kg);

            $summary[$category] = [
                'category' => $category,
                'flw_group' => $flw['group'],
                'eu_code' => $flw['eu_code'],
                'total_kg' => round($rawKg, 2),
                'entry_count' => $categoryRows->sum('entry_count'),
                'by_reason' => $byReason,
                'cost' => self::categoryCost(
                    (float) $categoryRows->sum('entry_cost'),
                    $hasCostColumns ? (float) $categoryRows->sum('unpriced_kg') : $rawKg,
                    (int) $categoryRows->sum('priced_count'),
                    $prices[$category] ?? null,
                ),
                'co2e' => round($rawKg * self::CO2E_FACTORS[$category], 2),
            ];
        }

        return $summary;
    }

    /**
     * Grand totals across a summary built by buildSummary(). Cost is null when
     * no category has a price.
     *
     * @return array{cost: float|null, co2e: float}
     */
    public function totals(array $summary): array
    {
        $costs = array_filter(array_column($summary, 'cost'), fn ($cost) => $cost !== null);

        return [
            'cost' => $costs === [] ? null : round(array_sum($costs), 2),
            'co2e' => round(array_sum(array_column($summary, 'co2e')), 2),
        ];
    }

